#!/usr/bin/env python3
"""Fill empty tags/categories in content/news posts from a controlled vocabulary.

Run from the site root. Only posts with `tags = []` and `categories = []` are
touched.

Usage: python scripts/add_taxonomies.py [--write]   (default: dry run, prints a report)
"""
