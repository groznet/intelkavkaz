FALLBACK_CATEGORY = "Новости клуба"

# Ordered by priority; up to MAX_TAGS kept.
TAGS = [
    # games
    ("Что? Где? Когда?", r"Что\? Где\? Когда\?|ЧГК|ЧТОГДЕКОГДА|Что\? Где\? Кавказ"),
    ("Брэйн-ринг", r"[Бб]р[эе]йн-?\s?ринг|БРЭЙНРИНГ"),
    ("Своя игра", r"[Сс]воя игра|СВОЯИГРА|Своей игре"),
    ("Хамса", r"Хамса"),
    ("Квиз", r"[Кк]виз|КВИЗ"),
    # projects / events
    ("Лидер чтения города Грозный", r"Лидер чтения"),
    ("Игры разума", r"Игры разума"),
    ("Умножая таланты", r"Умножая таланты"),
    ("Папа, мама, я — интеллектуальная семья", r"Папа, мама, я"),
    ("Защитник Отечества", r"Защитник Отечества"),
    ("Грозненский костёр Марины Цветаевой", r"Грозненский костёр|Цветаев"),
    ("Культурный Кавказ", r"Культурный Кавказ"),
    ("Хаархьама", r"Хаархьама"),
    ("Мудрость Ислама", r"Мудрость Ислама"),
    ("Международная Исламская Миссия", r"Международн[а-я]+ Исламск[а-я]+ Миссия|Проект МИМ|МИМ\b"),
    ("Турнир памяти Ахмата-Хаджи Кадырова", r"памяти (?:Первого Президента[^.]*)?А(?:хмат[а-я-]*|-Х\.А\.)[ -]*Кадыров|Знать\. Помнить\. Чтить|Кубок Кадырова"),
    ("Форум классных руководителей", r"Форум[а-я]* классных руководителей|ФКР"),
    ("Машук", r"(?i:Машук)"),
    ("Маяк Севера", r"Маяк Севера"),
    ("Фестиваль «Перекрёсток»", r"Перекрёсток|Перекресток"),
    ("Назначения", r"назначением на должность|избранием нового президента"),
    ("Фотоотчёт", r"\bфото\b|^Без названия"),
    ("Грант Президентского фонда культурных инициатив", r"Президентск[а-я]+ [Фф]онд[а-я]* культурных инициатив"),
    ("Фонд президентских грантов", r"[Фф]онд[а-я]* президентск[а-я]+ грантов"),
    ("Грант Главы ЧР", r"грант[а-я]* Главы Чеченской"),
    ("Грант Мэра Грозного", r"Грант[а-я]* Мэра"),
    ("Филиалы клуба", r"филиал"),
    ("Мастер-класс", r"[Мм]астер-класс"),
    ("Открытие филиала", r"открытие[^.]{0,40}филиал"),
    # who
    ("Лом-Али Мовлатов", r"Мовлатов[а-я]* Лом-?\s?[Аа]ли|Лом-?\s?[Аа]ли Мовлатов"),
    ("Иса Есиев", r"Есиев[а-я]* Ис[ауы]|Иса Есиев"),
    ("Саидмагомед Музаев", r"Музаев[а-я]* Сайд-?\s?[Мм]агомед|Музаев Саидмагомед|Сайд-?Магомед"),
    ("Команда «13»", r"команд[а-я]+ ?[«\"“]?13\b|команды 13"),
    # orgs
    ("Интеллектуальная Россия", r"Интеллектуальная Россия|ВАОО|ВПП"),
    ("МИЦ СКФО", r"МИЦ|Мицскфо"),
    ("Департамент образования Мэрии Грозного", r"Департамент[а-я]* образования Мэрии"),
    ("Национальная библиотека ЧР", r"[Нн]ациональн[а-я]+ библиотек"),
    ("Единая Россия", r"Единая Россия|ЕДИНАЯ РОССИЯ|Единой России"),
    ("ЧГПУ", r"ЧГПУ|педагогическом университете|педагогическом университет"),
    ("ГГНТУ", r"ГГНТУ"),
    ("Лингвистическая школа", r"Лингвистическ"),
    ("СОШ №23", r"СОШ ?№ ?23|СОШ 23"),
    ("ЧГТРК «Грозный»", r"ЧГТРК|ГТРК|телерадиокомпани"),
    # themes
    ("Советник директора по воспитанию", r"[Сс]оветник[а-я]* директора по воспитанию"),
    ("Профориентация", r"профориентац|профессиональной ори"),
    ("Учитель года", r"Учитель года"),
    ("Рамадан", r"Рамадан"),
    ("Хиджра", r"хиджр"),
    ("Пророк Мухаммад", r"пророка Мухаммад|ПРОРОКА МУХАМ|Пророка Мухаммад"),
    ("Выборы", r"выбор"),
    ("Патриотическое воспитание", r"патриотическ|Победы в Великой|Отечеств"),
    # geography (last; they are context, not topic)
    ("Грозный", r"Грозн"),
    ("Аргун", r"Аргун"),
    ("Шалинский район", r"Шалинск|Автуры"),
    ("Серноводский район", r"Серновод"),
    ("Шатойский район", r"Шатой"),
    ("Итум-Калинский район", r"Итум-Кал"),
    ("Веденский район", r"Веден"),
    ("Надтеречный район", r"Надтеречн"),
    ("Урус-Мартановский район", r"Урус-Мартан"),
    ("Ачхой-Мартановский район", r"Ачхой-Мартан"),
    ("Дагестан", r"Дагестан|Махачкал"),
    ("Ингушетия", r"Ингуш|Магас|Назран"),
    ("Северная Осетия", r"Алани|Владикавказ"),
    ("Москва", r"в Москве|Москов"),
    ("Пятигорск", r"Пятигорск"),
]
MAX_TAGS = 8
MIN_TAGS = 2
# Geography is tagged only when it is not already implied by many posts: skip bare
# "Грозный" for the 60 school-visit posts (it adds no filtering value).
GENERIC_TAGS = {"Грозный"}

# Manual fixes by post folder name (cats, tags-or-None to keep computed tags).
OVERRIDES = {
    "19_23-22_852294098_23": (["Турниры и игры"], ["Интеллектуальные игры"]),
    "09_00-57_852294098_74": (["Проекты и гранты"], None),
    "09_01-26_852294098_75": (["Общественная жизнь"], None),
    "08_22-59_852294098_824": (["Турниры и игры"], ["Что? Где? Когда?", "Интеллектуальные игры"]),
    "11_23-08_852294098_1316": (["Награды и достижения"], None),
}

files = sorted(glob.glob("content/news/*/*/*/index.md"))
cat_count = collections.Counter()
tag_count = collections.Counter()
weak = []

for n, path in enumerate(files):
    raw = open(path, encoding="utf8").read()
    head, sep, rest = raw.partition("\n+++\n")  # front matter / body split
    # front matter is between first +++ and second +++
    if not (re.search(r"^tags = \[\]", raw, re.M) and re.search(r"^categories = \[\]", raw, re.M)):
        continue
    parts = raw.split("+++", 2)
    fm, body = parts[1], parts[2]
    title = re.search(r'^title = "(.*)"', fm, re.M)
    text = (title.group(1) if title else "") + " " + body.split("## Комментарии")[0]

    cat_text = re.sub(r"форум[а-я]* «Лидер чтения города Грозный»", "", text)
    cats = [name for name, rx in CATEGORIES if re.search(rx, cat_text)]
    if len(cats) > 1 and "Поздравления" in cats:
        cats.remove("Поздравления")
    cats = cats[:2]
    if "Лидер чтения" in text and "Турниры и игры" in [n for n, rx in CATEGORIES if re.search(rx, cat_text)] and "Турниры и игры" not in cats:
        cats = ["Проекты и гранты", "Турниры и игры"]
    if not cats:
        cats = [FALLBACK_CATEGORY]

    tags = []
    for name, rx in TAGS:
        if name in cats or name in tags:
            continue
        if re.search(rx, text):
            tags.append(name)
    specific = [t for t in tags if t not in GENERIC_TAGS]
    if len(specific) >= MIN_TAGS:
        tags = specific
    tags = tags[:MAX_TAGS]
    if len(tags) < MIN_TAGS and "Турниры и игры" in cats and "Интеллектуальные игры" not in tags:
        tags.append("Интеллектуальные игры")
    if len(tags) < MIN_TAGS:
        weak.append((n, path, cats, tags, text[:80]))

    key = path.split("/")[-2]
    if key in OVERRIDES:
        cats = OVERRIDES[key][0]
        if OVERRIDES[key][1] is not None:
            tags = OVERRIDES[key][1]
    cat_count.update(cats)
    tag_count.update(tags)

    if WRITE:
        arr = lambda xs: "[" + ", ".join(json.dumps(x, ensure_ascii=False) for x in xs) + "]"
        new_fm, c1 = re.subn(r"^tags = \[\]", "tags = " + arr(tags), fm, flags=re.M)
        new_fm, c2 = re.subn(r"^categories = \[\]", "categories = " + arr(cats), new_fm, flags=re.M)
        if c1 != 1 or c2 != 1:
            print("SKIP (no empty arrays):", path)
            continue
        tmp = path + ".tmp"
        open(tmp, "w", encoding="utf8").write("+++" + new_fm + "+++" + body)
        import os
        os.replace(tmp, path)

print("categories:", cat_count.most_common())
print("tags:", len(tag_count))
for t, c in tag_count.most_common():
    print(f"  {c:4d} {t}")
print("weak (<%d tags): %d" % (MIN_TAGS, len(weak)))
for w in weak:
    print("  ", w)
