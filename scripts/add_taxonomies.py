    ("Религия и традиции", r"Рамадан|хиджр|[Пп]ророк|Ислам|ислам|Коран"),
    ("Культура и просвещение", r"Цветаев|Выставк"),
    ("Поздравления", r"[Пп]оздравля"),
    ("Общественная жизнь", r"Единая Россия|ЕДИНАЯ РОССИЯ|выбор|НКО|Общественн[а-я]+ [Пп]алат|Национальный Совет|Национальный совет"),
